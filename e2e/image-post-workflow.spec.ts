import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';

test('图文上传排序、独立AI验收、品牌退回与通过、版本失效和移动端', async ({ page, request }) => {
  test.setTimeout(60_000);
  test.skip(process.env.E2E_IMAGE_MODEL_FIXTURE !== '1', '需显式启用隔离服务的图文模型固定输出，不调用真实供应商');
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const headers = () => ({ 'Idempotency-Key': crypto.randomUUID() });
  const projectResponse = await request.post('/api/v1/projects', { data: { name: `椿日记图文验收-${Date.now()}`, brandName: '椿日品牌', platforms: ['xiaohongshu'] }, headers: headers() });
  expect(projectResponse.status()).toBe(201);
  const project = (await projectResponse.json()).data;
  const rule = (text: string) => ({ text, criterion: '按品牌材料逐项核对，不清楚的内容待人工确认', importance: 'must', category: '品牌信息' });
  const publish = await request.post(`/api/v1/projects/${project.id}/publish-task`, { data: {
    creatorName: '椿日记', platform: 'xiaohongshu', scriptRules: [rule('脚本产品信息准确')], videoRules: [rule('视频展示产品')],
    imageRules: [rule('封面品牌与产品清晰完整'), rule('标题正文与图片信息一致')], scriptConfirmed: true, videoConfirmed: true, confirmationNote: '品牌逐条确认三类规则',
  }, headers: headers() });
  expect(publish.status()).toBe(201);
  const taskId = (await publish.json()).data.id;
  const settings = (await (await request.get('/api/v1/settings/models')).json()).data;
  const configured = await request.put('/api/v1/settings/models', { data: { endpoint: 'https://models.example.com/v1', model: 'e2e-image-fixture', revision: settings.revision, apiKey: 'sk-browser-fixture-only' } });
  expect(configured.ok()).toBeTruthy();
  const fixture = (color: string, label: string) => execFileSync(resolve('.venv/Scripts/python.exe'), ['-c', `from PIL import Image,ImageDraw,ImageFont; import sys; im=Image.new('RGB',(600,760),'${color}');d=ImageDraw.Draw(im);f=ImageFont.truetype('C:/Windows/Fonts/arial.ttf',30); d.text((45,50),'CHUN / DAILY NOTES',fill='#1b5444',font=f);d.rounded_rectangle((170,180,430,610),radius=28,fill='#f5f0df',outline='#568f78',width=3);d.ellipse((240,300,360,420),fill='#9fc5ab');d.text((225,465),'BRAND A',fill='#315b48',font=f);d.text((45,675),'${label}',fill='#315b48',font=f);im.save(sys.stdout.buffer,format='PNG')`]);
  const cover = fixture('#e3efe4', 'A CALM MORNING'), detail = fixture('#dfeceb', 'EVERYDAY MOMENTS');
  await page.addInitScript(() => localStorage.setItem('review-demo-role', 'creator'));
  await page.goto(`/creator/projects/${project.id}/tasks/${taskId}/image`);
  await expect(page.getByRole('navigation', { name: '合作验收类型' })).toBeVisible();
  await page.getByRole('link', { name: /^视频验收/ }).click();
  await expect(page.getByText('可提交完整成片', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '上传 / 验收视频', exact: true })).toBeEnabled();
  await page.getByRole('link', { name: /^图文验收/ }).click();
  await page.getByRole('button', { name: '提交图文', exact: true }).click();
  await page.getByLabel('图文标题', { exact: true }).fill('把日常过成喜欢的样子');
  await page.getByLabel('正文与话题', { exact: true }).fill('给忙碌的一天，留下一点松弛。\n品牌A陪伴我的日常生活。\n#椿日记 #日常好物');
  await page.getByLabel('添加图文图片', { exact: true }).setInputFiles([{ name: 'morning.png', mimeType: 'image/png', buffer: cover }, { name: 'details.png', mimeType: 'image/png', buffer: detail }]);
  await expect(page.locator('.image-post-editor-image')).toHaveCount(2);
  await page.getByRole('button', { name: '上移第2张图片', exact: true }).click();
  await expect(page.locator('.image-post-editor-image').first()).toContainText('details.png');
  await page.getByLabel('第1张图片配文').fill('让生活慢下来');
  await page.getByRole('button', { name: '保存并进行 AI 验收', exact: true }).click();
  await page.getByRole('button', { name: '确认保存并验收', exact: true }).click();
  await expect(page.getByText('AI 必须项通过，仍需品牌复核', { exact: true })).toBeVisible();
  await expect(page.locator('.image-post-thumbnails button')).toHaveCount(2);
  await expect(page.locator('.image-post-stage')).toContainText('让生活慢下来');
  const state = (await (await request.get(`/api/v1/tasks/${taskId}/image-posts`)).json()).data;
  expect(state.review.result.providerRequestIds).toEqual(['e2e-image-fixture']);
  expect(state.brandApproved).toBe(false);
  expect((await (await request.get(`/api/v1/tasks/${taskId}/workflow`)).json()).data.videoAllowed).toBe(true);
  await page.getByRole('button', { name: '切换到品牌端', exact: true }).click();
  await expect(page).toHaveURL(`/projects/${project.id}/tasks/${taskId}/image`);
  await page.getByRole('button', { name: '品牌复核', exact: true }).click();
  await page.getByRole('radio', { name: '退回修改', exact: true }).check();
  await page.getByLabel('图文品牌复核意见').fill('请补充正文的具体体验，再提交新版。');
  await page.getByText('已核对当前版本全部文字与图片', { exact: true }).click();
  await page.getByRole('button', { name: '保存品牌决定', exact: true }).click();
  await expect(page.getByText('品牌退回修改', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '切换到达人端', exact: true }).click();
  await expect(page).toHaveURL(`/creator/projects/${project.id}/tasks/${taskId}/image`);
  await page.getByRole('button', { name: '提交修改版图文', exact: true }).click();
  await page.getByLabel('正文与话题', { exact: true }).fill('给忙碌的一天，留下一点松弛。\n品牌A的产品细节是我喜欢的日常体验。\n#椿日记 #日常好物');
  await page.getByRole('button', { name: '保存并进行 AI 验收', exact: true }).click();
  await page.getByRole('button', { name: '确认保存并验收', exact: true }).click();
  await expect(page.getByText('AI 必须项通过，仍需品牌复核', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '切换到品牌端', exact: true }).click();
  await page.getByRole('button', { name: '品牌复核', exact: true }).click();
  await page.getByLabel('图文品牌复核意见').fill('已核对当前标题正文及两张图片，允许发布此版本。');
  await page.getByText('已核对当前版本全部文字与图片', { exact: true }).click();
  await page.getByRole('button', { name: '保存品牌决定', exact: true }).click();
  await expect(page.getByText('品牌已通过图文', { exact: true }).last()).toBeVisible();
  await page.getByRole('button', { name: '切换到达人端', exact: true }).click();
  for (const width of [1366, 1440, 1920]) {
    await page.setViewportSize({ width, height: width === 1366 ? 768 : 1080 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 2)).toBeTruthy();
    const panels = await page.locator('.media-review-grid > .ant-card').evaluateAll(nodes => nodes.map(n => { const r = n.getBoundingClientRect(); return { top: r.top, bottom: r.bottom }; }));
    expect(panels).toHaveLength(2); expect(Math.abs(panels[0].top - panels[1].top)).toBeLessThan(2);
    expect(panels.every(p => p.bottom <= (width === 1366 ? 768 : 1080))).toBeTruthy();
    await page.screenshot({ path: `test-results/image-post-desktop-${width}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: '把日常过成喜欢的样子' })).toBeVisible();
  const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].map(el => ({ tag: el.tagName, class: el.className, right: el.getBoundingClientRect().right, width: el.getBoundingClientRect().width })).filter(el => el.width && el.right > window.innerWidth + 1).slice(0, 12));
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), { message: JSON.stringify(overflow) }).toBeTruthy();
  await page.screenshot({ path: 'test-results/image-post-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.getByRole('button', { name: '提交修改版图文', exact: true }).click();
  await page.getByLabel('图文标题', { exact: true }).fill('新版标题，需要重新验收');
  await page.getByRole('button', { name: '保存版本（不调用 AI）', exact: true }).click();
  await expect(page.getByText('此版本尚无适用于当前图文规则的验收，请重新验收', { exact: true })).toBeVisible();
  const changed = (await (await request.get(`/api/v1/tasks/${taskId}/image-posts`)).json()).data;
  expect(changed.brandApproved).toBe(false);
  expect(changed.versions).toHaveLength(3);
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.getByRole('combobox', { name: '图文版本' }).click();
  await page.getByText('图文 V1 · 历史', { exact: true }).click();
  await expect(page.getByText('正在查看历史版本；品牌决定和重新验收仅针对最新版本', { exact: true })).toBeVisible();
  await expect(page.getByText('历史意见 · 品牌退回修改', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
