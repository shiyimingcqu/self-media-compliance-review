import { test, expect } from '@playwright/test';

test('达人确认修改、逐条异议、品牌补充与裁决、进度看板和站内催办（不计费）', async ({ page, request }) => {
  test.setTimeout(120_000);
  test.skip(process.env.E2E_DISCUSSION_FIXTURE !== '1', '需启用隔离服务固定响应，不访问真实模型');
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const headers = () => ({ 'Idempotency-Key': crypto.randomUUID() });
  const project = (await (await request.post('/api/v1/projects', { headers: headers(), data: { name: `异议闭环-${Date.now()}`, brandName: '品牌A', platforms: ['xiaohongshu'] } })).json()).data;
  const rule = { text: '展示品牌A产品', criterion: '产品可辨认即可，不要求每镜出现', importance: 'must', category: '产品' };
  const published = await request.post(`/api/v1/projects/${project.id}/publish-task`, { headers: headers(), data: { creatorName: '异议测试达人', platform: 'xiaohongshu', scriptRules: [rule], videoRules: [rule], scriptConfirmed: true, videoConfirmed: true, confirmationNote: '固定测试规则' } });
  expect(published.status(), await published.text()).toBe(201);
  const task = (await published.json()).data.id;
  const cfg = (await (await request.get('/api/v1/settings/models')).json()).data;
  expect((await request.put('/api/v1/settings/models', { data: { endpoint: 'https://models.example.com/v1', model: 'e2e-discussion-fixture', apiKey: 'sk-test-fixture', revision: cfg.revision } })).ok()).toBeTruthy();
  const submitted = await request.post(`/api/v1/tasks/${task}/scripts`, { headers: headers(), data: { inputType: 'text', text: '镜头1：展示品牌A产品。随后自然介绍使用感受。' } });
  expect(submitted.ok(), await submitted.text()).toBeTruthy();
  const view = (await (await request.get(`/api/v1/tasks/${task}/workflow`)).json()).data;
  const review = await request.post(`/api/v1/tasks/${task}/workflow/script-reviews`, { headers: headers(), data: { scriptVersionId: view.currentScript.scriptVersionId, contextKey: view.contextKey, configRevision: cfg.revision + 1, allowRealCall: true } });
  expect((await review.json()).data.status).toBe('succeeded');
  await page.addInitScript(() => { if (!localStorage.getItem('review-demo-role')) localStorage.setItem('review-demo-role', 'creator'); });
  await page.goto(`/creator/projects/${project.id}/tasks/${task}`);
  await page.getByRole('button', { name: '收到，我去修改', exact: true }).click();
  await expect(page.getByRole('button', { name: '已收到，修改中', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '我对 AI 有异议', exact: true }).click();
  await page.getByRole('button', { name: '对这条提出异议', exact: true }).click();
  await page.getByLabel('异议材料位置', { exact: true }).fill('第1行');
  await page.getByLabel('异议具体理由', { exact: true }).fill('第一行已经安排展示品牌A产品，请核对原稿。');
  await page.getByRole('button', { name: '提交异议给品牌', exact: true }).click();
  await expect(page.getByText('第一行已经安排展示品牌A产品，请核对原稿。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '关闭', exact: true }).last().click();
  await page.getByRole('button', { name: '切换到品牌端', exact: true }).click();
  await page.goto(`/feedback?projectId=${project.id}`);
  await expect(page.getByRole('cell', { name: '有异议', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '异议处理', exact: true }).click();
  await page.getByRole('button', { name: '查看并裁决', exact: true }).click();
  await expect(page.getByText('镜头1：展示品牌A产品。随后自然介绍使用感受。', { exact: true }).last()).toBeVisible();
  await page.getByLabel('品牌裁决理由', { exact: true }).fill('请补充说明产品展示安排，品牌再核对。');
  await page.getByRole('checkbox', { name: '已核对本次原始材料、规则及相关证据', exact: true }).check();
  await page.getByRole('button', { name: '提交品牌裁决', exact: true }).click();
  await expect(page.getByText('请补充说明产品展示安排，品牌再核对。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '关闭', exact: true }).last().click();
  await page.getByRole('button', { name: '切换到达人端', exact: true }).click();
  await page.goto(`/creator/projects/${project.id}/tasks/${task}`);
  await page.getByRole('button', { name: '查看异议与回复', exact: true }).click();
  await page.getByLabel('异议具体理由', { exact: true }).fill('补充说明：镜头1就是产品特写，后续也有使用过程。');
  await page.getByRole('button', { name: '补充说明并通知品牌', exact: true }).click();
  await expect(page.getByText('补充说明：镜头1就是产品特写，后续也有使用过程。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '关闭', exact: true }).last().click();
  await page.getByRole('button', { name: '切换到品牌端', exact: true }).click();
  await page.goto(`/feedback?tab=disputes&projectId=${project.id}`);
  await page.getByRole('button', { name: '查看并裁决', exact: true }).click();
  await page.getByLabel('异议裁决结果', { exact: true }).click();
  await page.getByText('采纳异议 · 本条人工通过', { exact: true }).click();
  await page.getByLabel('品牌裁决理由', { exact: true }).fill('核对原稿后确认是AI误判，采纳异议。');
  await page.getByRole('checkbox', { name: '已核对本次原始材料、规则及相关证据', exact: true }).check();
  await page.getByRole('button', { name: '提交品牌裁决', exact: true }).click();
  await expect(page.getByText('核对原稿后确认是AI误判，采纳异议。', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/brand-dispute-ruling.png' });
  await page.getByRole('button', { name: '关闭', exact: true }).last().click();
  await page.getByRole('tab', { name: '达人进度看板', exact: true }).click();
  await expect(page.getByRole('cell', { name: '待品牌确认', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '催办达人', exact: true }).click();
  await page.getByLabel('催办内容', { exact: true }).fill('请准备后续视频成片，脚本争议已处理。');
  await page.getByRole('button', { name: '发送站内催办', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByText('达人未读', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/creator-progress-board.png' });
  await page.getByRole('button', { name: '切换到达人端', exact: true }).click();
  await page.goto('/creator');
  await expect(page.getByText('请准备后续视频成片，脚本争议已处理。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '收到', exact: true }).click();
  await expect(page.getByText('请准备后续视频成片，脚本争议已处理。', { exact: true })).not.toBeVisible();
  await page.getByRole('button', { name: '切换到品牌端', exact: true }).click();
  await page.goto(`/feedback?projectId=${project.id}`);
  await expect(page.getByText('达人已读', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: '达人进度与异议', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2)).toBeTruthy();
  await page.screenshot({ path: 'test-results/creator-progress-mobile.png' });
  expect(errors).toEqual([]);
});
