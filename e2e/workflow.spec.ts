import { test, expect } from '@playwright/test';
const base = 'http://127.0.0.1:8001/api/v1';
const key = () => ({ 'Idempotency-Key': crypto.randomUUID() });

test('切换达人端与品牌端：必须项未通过不送审，通过后品牌复核', async ({ page, request }) => {
  test.setTimeout(90000);
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const p = (await (await request.post(`${base}/projects`, { headers: key(), data: { name: '品牌A春季合作', brandName: '品牌A', platforms: ['douyin'] } })).json()).data;
  const file = (await (await request.post(`${base}/files`, { headers: key(), multipart: { purpose: 'brief', file: { name: 'spring-brief.txt', mimeType: 'text/plain', buffer: Buffer.from('必须准确介绍品牌A，不得保证效果。') } } })).json()).data;
  const brief = (await (await request.post(`${base}/projects/${p.id}/briefs`, { headers: key(), data: { fileId: file.id, title: '春季合作 Brief', platforms: ['douyin'] } })).json()).data;
  const draft = { text: '品牌审核规则', criterion: '必须提及品牌A，不得保证效果。', category: '脚本审核规则', importance: 'must' };
  const taskResponse = await request.post(`${base}/projects/${p.id}/publish-task`, { headers: key(), data: { creatorName: '达人小林', platform: 'douyin', scriptRules: [draft], videoRules: [{ ...draft, category: '画面' }], scriptConfirmed: true, videoConfirmed: true, confirmationNote: '品牌保存规则', sourceVersionId: brief.sourceVersionId } });
  expect(taskResponse.status()).toBe(201);
  const task = (await taskResponse.json()).data;
  let current: Record<string, any> | null = null, calls = 0;
  await page.route('**/api/v1/workflow/script-reviews/*/images/*', route => route.fulfill({ contentType: 'image/png', body: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl2nS8AAAAASUVORK5CYII=', 'base64') }));
  const approval = { id: 'approval-ui', note: '内容符合品牌要求，确认通过', created_at: new Date().toISOString() };
  await page.route('**/api/v1/settings/models', route => route.fulfill({ json: { data: { endpoint: 'https://models.example.com/v1', model: 'mock-model', hasKey: true, revision: 1, maxInlineBytes: 25000000 } } }));
  await page.route('**/api/v1/settings/models/decomposition', route => route.fulfill({ json: { data: { endpoint: 'https://models.example.com/v1', model: 'mock-model', hasKey: true, revision: 1, maxInlineBytes: 25000000 } } }));
  await page.route(`**/api/v1/tasks/${task.id}/workflow`, async route => {
    const response = await route.fetch(); const body = await response.json();
    if (current && body.data.currentScript?.scriptVersionId === current.currentScript.scriptVersionId) body.data = current;
    await route.fulfill({ response, json: body });
  });
  await page.route('**/api/v1/creator/tasks', async route => {
    const response = await route.fetch(); const body = await response.json();
    body.data = body.data.map((t: any) => t.id === task.id && current ? { ...t, scriptAcceptance: current.scriptAcceptance, brandApproved: !!current.scriptApproval } : t);
    await route.fulfill({ response, json: body });
  });
  await page.route('**/api/v1/workflow/review-queue', async route => route.fulfill({ json: { data: current?.brandReviewAllowed && !current.scriptApproval ? [{ id: task.id, creator_name: '达人小林', platform: 'douyin', project_id: p.id, project_name: p.name, scope: 'script', submittedAt: new Date().toISOString(), summary: '必须项验收通过' }] : [] } }));
  await page.route(`**/api/v1/tasks/${task.id}/scripts/submit-and-review`, async route => {
    expect(route.request().postDataJSON().allowRealCall).toBe(true); calls++;
    // No supplier Key exists in the isolated backend. Persist the real script, then mock only AI output.
    const response = await route.fetch(); const saved = (await response.json()).data.script;
    const view = (await (await request.get(`${base}/tasks/${task.id}/workflow`)).json()).data;
    const text = view.currentScript.text || view.currentScript.sourceMap.map((b: any) => b.text).join('\n');
    const passed = !text.includes('保证有效'), ruleId = view.standardSets.script.rules[0].id;
    const check = { rule_id: ruleId, rule_number: 1, requirement: '不得保证产品效果', verdict: passed ? 'compliant' : 'non_compliant', quote: passed ? '' : '保证有效', reason: passed ? '未发现保证效果的表述' : '脚本包含未经确认的效果保证' };
    const acceptance = { passed, status: passed ? 'passed' : 'needs_changes', checks: [check], blockingCount: passed ? 0 : 1, message: passed ? '必须项验收通过，已进入品牌待审' : '还有1项必须项未通过，请修改脚本后重新提交' };
    const review = { id: `mock-review-${calls}`, scriptVersionId: saved.scriptVersionId, contextKey: view.contextKey, status: 'succeeded', snapshot: { multimodal: { images: [{ id: 'mock-picture', locations: ['视频脚本!E10'], width: 1, height: 1 }], uncovered: [], incomplete: false } }, acceptance, createdAt: saved.createdAt, result: { report: { image_checks: [{ image_id: 'mock-picture', description: '参考图中的产品展示已核对', rule_ids: [ruleId] }], summary: passed ? '必须项全部符合，等待品牌复核' : '请删除效果保证后重新提交', mandatory_checks: [check], findings: [{ rule_id: ruleId, rule_number: 1, image_ids: ['mock-picture'], verdict: check.verdict, quote: check.quote, description: check.reason, suggestion: passed ? '' : '删除保证有效，改为真实使用体验' }] } } };
    current = { ...view, scriptReview: review, scriptReviews: [review], scriptAcceptance: acceptance, brandReviewAllowed: passed, scriptApproval: null };
    await route.fulfill({ status: 201, json: { data: { script: saved, autoReview: review, autoReviewError: null } } });
  });
  await page.route(`**/api/v1/tasks/${task.id}/workflow/decisions`, async route => {
    expect(current?.scriptAcceptance.passed).toBe(true);
    const input = route.request().postDataJSON(); expect(input.reviewedMaterial).toBe(true);
    current = { ...current!, scriptApproval: approval, videoAllowed: true, stage: 'video' };
    await route.fulfill({ json: { data: { id: approval.id, stage: 'video' } } });
  });
  await page.goto(`/projects/${p.id}`);
  await page.getByRole('button', { name: '切换到达人端', exact: true }).click();
  await expect(page.getByRole('heading', { name: '我的合作', exact: true })).toBeVisible();
  await page.getByText('脚本验收', { exact: true }).click();
  await expect(page.getByText('春季合作 Brief', { exact: true }).first()).toBeVisible();
  await expect(page.getByRole('button', { name: '编辑项目规则' })).toHaveCount(0);
  await page.getByLabel('上传对应Brief的脚本').setInputFiles({ name: 'script.txt', mimeType: 'text/plain', buffer: Buffer.from('品牌A，保证有效。') });
  await page.getByRole('button', { name: '提交脚本并进行AI验收', exact: true }).click();
  await expect(page.locator('.script-review-comments .review-comment-toolbar')).toContainText('待修改');
  await expect(page.getByRole('button', { name: '确认品牌审查结果' })).toHaveCount(0);
  await expect(page.getByRole('article', { name: '审核评论 1', exact: true })).toContainText('第 1 条 · 需修改');
  await page.getByRole('button', { name: '审核详情', exact: true }).click();
  await expect(page.getByText('图片审核说明 · 1 张（原图见左侧「图片」）', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '审核详情', exact: true }).click();
  await page.getByRole('tab', { name: '图片 · 1', exact: true }).click();
  await expect(page.getByRole('img', { name: '脚本原图 视频脚本!E10' })).toBeVisible();
  await page.screenshot({ path: 'test-results/creator-needs-changes.png', fullPage: true });
  await page.getByRole('button', { name: '切换到品牌端', exact: true }).click();
  await expect(page.getByText('尚未进入品牌待审', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '确认品牌审查结果' })).toHaveCount(0);
  await page.getByRole('menuitem').filter({ hasText: '待品牌审核' }).click();
  await expect(page.getByText('暂无待品牌确认的审核结果')).toBeVisible();
  await page.getByRole('button', { name: '切换到达人端', exact: true }).click();
  await page.getByText('脚本验收', { exact: true }).click();
  await page.getByRole('button', { name: '提交修改后的脚本', exact: true }).click();
  await page.getByRole('radio', { name: '粘贴脚本', exact: true }).check();
  await page.getByRole('textbox', { name: '达人脚本正文' }).fill('品牌A，介绍产品口味与真实使用体验。');
  await page.getByRole('button', { name: '提交脚本并进行AI验收', exact: true }).click();
  await expect(page.locator('.script-review-comments .review-comment-toolbar')).toContainText('必须项通过');
  await page.getByRole('button', { name: '切换到品牌端', exact: true }).click();
  await page.getByRole('menuitem').filter({ hasText: '待品牌审核' }).click();
  await expect(page.getByText('达人小林', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: '进入复核 →', exact: true }).click();
  await page.getByRole('textbox', { name: '品牌审查意见' }).fill(approval.note);
  await page.getByRole('checkbox', { name: '我已核对脚本与品牌要求' }).check();
  await page.getByRole('button', { name: '确认品牌审查结果', exact: true }).click();
  await expect(page.locator('main').getByText('品牌已确认通过', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/brand-script-review.png', fullPage: true });
  await page.getByRole('button', { name: '切换到达人端', exact: true }).click();
  await expect(page.getByText('品牌已通过脚本', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: '切换到品牌端', exact: true })).toBeVisible();
  await page.unrouteAll({ behavior: 'wait' });
  expect(calls).toBe(2); expect(errors).toEqual([]);
});
