import { test, expect } from '@playwright/test';
const base='http://127.0.0.1:8001/api/v1';
const headers=()=>({'Idempotency-Key':crypto.randomUUID()});

test('长事实卡移出项目页，原页图片与事实分栏定位，独立滚动和返回达人', async ({page,request})=>{
  const p=(await (await request.post(`${base}/projects`,{headers:headers(),data:{name:'麦咖啡 Brief 对照与达人一屏验收',brandName:'麦咖啡',platforms:['douyin']}})).json()).data;
  const template=(await (await request.get(`${base}/workflow/standard-templates`)).json()).data[0];
  await request.post(`${base}/projects/${p.id}/standards/confirm`,{headers:headers(),data:{scriptRules:template.scriptRules,videoRules:template.videoRules,scriptConfirmed:true,videoConfirmed:true,confirmationNote:'测试规则',revision:0}});
  for(let i=1;i<=5;i++) await request.post(`${base}/projects/${p.id}/creators`,{headers:headers(),data:{creatorName:`合作达人${i}`,platform:'douyin'}});
  const blocks=Array.from({length:27},(_,i)=>({id:`vision:run:${i+1}:text`,pageNo:i+1,text:`第${i+1}页原文，产品全名芝士浓奶铁，产品信息清晰展示。`,origin:'ai-visual-extraction'}));
  const products=Array.from({length:30},(_,i)=>({value:`产品要求 ${String(i+1).padStart(2,'0')}`,blockId:blocks[i%27].id,quote:blocks[i%27].text}));
  const pending=Array.from({length:5},(_,i)=>({group:'freeform',value:`待核对问题 ${i+1}`,pageNo:i+2,source:'text',quote:'省略……引文',reason:'引文存在省略，需要对照原页'}));
  const brief={title:'麦咖啡芝士浓奶铁投放Brief.pdf',revision:1,sourceVersionId:'source',fileId:'file',pageCount:27,blocks,uncoveredSources:['page:2','page:3'],pageChecks:[{id:'page-check-2',pageNo:2,visionRunId:'run',reasons:['内部ID的用途不确定']},{id:'page-check-3',pageNo:3,visionRunId:'run',reasons:['示例截图中个别评论小字未识清']}],visionRunId:'run',processing:{id:'flow',sourceVersionId:'source',status:'succeeded'},visualRun:{id:'run',sourceVersionId:'source',status:'succeeded',snapshot:{model:'mock',pages:blocks.map(b=>({pageNo:b.pageNo,width:1200,height:900}))}}};
  let pageReviews=0;
  await page.route(`**/api/v1/projects/${p.id}/brief/pages/review`,r=>{
    const body=r.request().postDataJSON();expect(body.sourceVersionId).toBe('source');
    expect(['confirmed','irrelevant']).toContain(body.action);pageReviews++;
    brief.pageChecks=brief.pageChecks.filter(check=>check.id!==body.checkId);
    return r.fulfill({json:{data:{pageChecks:brief.pageChecks}}});
  });
  await page.route(`**/api/v1/projects/${p.id}/brief`,r=>r.fulfill({json:{data:{projectId:p.id,revision:1,brief}}}));
  await page.route(`**/api/v1/projects/${p.id}/brief/facts`,r=>r.fulfill({json:{data:{sourceVersionId:'source',facts:{brand:{value:'麦咖啡',blockId:blocks[0].id,quote:blocks[0].text},products,sellingPoints:products.map(x=>({...x,value:'卖点 '+x.value})),requiredTerms:products.slice(0,24).map(x=>({...x,value:'必提 '+x.value})),forbiddenTerms:[],publishRules:[],thresholds:[],freeform:[],warnings:['5 条事实待核对，其他有效事实可继续使用。']},lastRun:{id:'facts',status:'succeeded',result:{pendingFacts:pending}}}}}));
  await page.route('**/brief/vision/run/pages/*',r=>{
    const n=r.request().url().split('/').pop();
    return r.fulfill({contentType:'image/svg+xml',body:`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="900"><rect width="1200" height="900" fill="#f6f3eb"/><rect x="70" y="100" width="100" height="6" fill="#a38750"/><text x="70" y="180" font-family="sans-serif" font-size="42" fill="#282824">McCafe · Brief / ${n}</text><text x="70" y="300" font-family="sans-serif" font-size="30" fill="#555">Product information and campaign requirements</text><rect x="70" y="380" width="1060" height="300" fill="#e5e1d6"/><text x="100" y="450" font-size="25" fill="#444">Original document page ${n}</text></svg>`});
  });
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1366,height:768});
  await page.goto(`/projects/${p.id}`);
  await expect(page.locator('.ant-table-row')).toHaveCount(5);
  await expect(page.getByText('产品要求 01',{exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'添加达人',exact:true})).toBeInViewport();
  await expect(page.locator('.project-creators-panel')).toBeInViewport();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+2)).toBeTruthy();
  await page.screenshot({path:'test-results/brief-project-compact.png',fullPage:true});
  await page.getByRole('button',{name:'查看解析内容',exact:true}).click();
  await expect(page).toHaveURL(/brief-review/);
  await expect(page.locator('.brief-fact-term')).toHaveCount(85);
  await expect(page.locator('.brief-fact-group')).toHaveCount(4);
  await page.getByText('产品要求 03',{exact:true}).click();
  await expect(page.getByAltText('Brief第3页')).toBeVisible();
  await expect(page.locator('.brief-fact-group blockquote')).toContainText('第3页原文');
  await page.getByRole('tab',{name:'待核对 7',exact:true}).click();
  await page.getByText('第 2 页有局部疑点',{exact:true}).click();
  await expect(page.getByAltText('Brief第2页')).toBeVisible();
  await page.screenshot({path:'test-results/brief-page-checks.png',fullPage:true,animations:'disabled'});
  await page.locator('.brief-review-fact').filter({hasText:'内部ID的用途不确定'}).getByRole('button',{name:'已核对',exact:true}).click();
  await expect(page.getByRole('tab',{name:'待核对 6',exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText('第 2 页有局部疑点',{exact:true})).toHaveCount(0);
  await page.locator('.brief-review-fact').filter({hasText:'示例截图中个别评论小字未识清'}).getByRole('button',{name:'不影响规则',exact:true}).click();
  await expect(page.getByRole('tab',{name:'待核对 5',exact:true})).toBeVisible();
  await page.getByText('待核对问题 4',{exact:true}).click();
  await expect(page.getByAltText('Brief第5页')).toBeVisible();
  await page.reload();
  await expect(page.getByAltText('Brief第5页')).toBeVisible();
  await page.getByRole('tab',{name:'事实卡 85',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+2)).toBeTruthy();
  expect(await page.locator('.brief-facts-scroll').evaluate(n=>n.scrollHeight>n.clientHeight)).toBe(true);
  await page.screenshot({path:'test-results/brief-review-desktop.png',fullPage:true});
  await page.getByLabel('搜索Brief事实').fill('产品要求 03');
  await expect(page.locator('.brief-fact-term')).toHaveCount(3);
  await page.getByLabel('搜索Brief事实').fill('');
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:'test-results/brief-review-mobile.png',fullPage:true});
  await page.getByRole('link',{name:'返回项目与达人',exact:true}).click();
  await expect(page.locator('.brief-overview-notice')).toHaveCount(0);
  expect(pageReviews).toBe(2);
  await expect(page.locator('.ant-table-row')).toHaveCount(5);
  expect(errors).toEqual([]);
});
