import { test, expect } from '@playwright/test';

test('脚本规则表格：筛选、分页、启用开关、编辑和保存回显（不调用模型）', async ({ page, request }) => {
  const headers = () => ({ 'Idempotency-Key': crypto.randomUUID() });
  const p = (await (await request.post('/api/v1/projects', { headers:headers(), data:{ name:'麦咖啡小红书',brandName:'麦咖啡',platforms:['xiaohongshu'] } })).json()).data;
  const template = (await (await request.get('/api/v1/workflow/standard-templates')).json()).data[0];
  const scriptRules = Array.from({length:12}, (_,i) => ({ text:`脚本须准确表达产品要求${i + 1}`,criterion:`涉及麦咖啡产品时，应准确传达品牌确认的信息。第${i + 1}条的判据不改变原文含义。`,category:i%2 ? '卖点要求' : '品牌信息',importance:i%2 ? 'suggested' : 'must',origin:'manual',sourceBlockId:'',sourceQuote:'' }));
  const response = await request.post(`/api/v1/projects/${p.id}/standards/confirm`, {headers:headers(),data:{revision:0,scriptRules,videoRules:template.videoRules,scriptConfirmed:true,videoConfirmed:true,confirmationNote:'固定测试'}});
  expect(response.ok(), await response.text()).toBeTruthy();
  await page.goto(`/projects/${p.id}/rules?type=script`);
  await expect(page.getByRole('heading', {name:'麦咖啡小红书 · 审核规则'})).toBeVisible();
  await expect(page.getByRole('region', {name:'AI 生成脚本规则'})).toBeVisible();
  await expect(page.locator('.script-rule-row')).toHaveCount(10);
  await page.locator('.script-rules-table .ant-pagination-item-2').click();
  await expect(page.locator('.script-rule-row')).toHaveCount(2);
  await page.getByLabel('搜索规则', {exact:true}).fill('12');
  await expect(page.locator('.script-rule-row')).toHaveCount(1);
  await expect(page.locator('.script-rule-row')).toContainText('产品要求12');
  await page.getByLabel('搜索规则', {exact:true}).fill('');
  await page.getByLabel('筛选规则重要性', {exact:true}).click();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  await expect(page.locator('.script-rule-row')).toHaveCount(6);
  // 启用开关：关掉第一条后行置灰并计入"停用"，再打开恢复
  const firstSwitch = page.getByRole('switch', { name: '启用脚本第1条', exact: true });
  await expect(firstSwitch).toBeChecked();
  await firstSwitch.click();
  await expect(page.locator('.script-rule-row').first()).toHaveClass(/is-disabled/);
  await expect(page.locator('.script-rules-table > footer')).toContainText('停用 1 条');
  await firstSwitch.click();
  await expect(page.locator('.script-rules-table > footer')).toContainText('停用 0 条');
  await page.getByRole('button', {name:'编辑第1条规则',exact:true}).click();
  await page.getByRole('textbox', {name:'第1条要求',exact:true}).fill('脚本须使用麦咖啡芝士浓奶铁全称');
  await page.getByRole('button', {name:'确认修改',exact:true}).click();
  await expect(page.locator('.script-rule-row').first()).toContainText('脚本须使用麦咖啡芝士浓奶铁全称');
  const saved = page.waitForResponse(r => r.url().endsWith('/standards/confirm') && r.request().method()==='POST');
  await page.getByRole('button', {name:'保存项目审核规则',exact:true}).click();
  expect((await saved).ok()).toBeTruthy();
  await expect(page.getByText('项目规则已保存', {exact:true})).toBeVisible();
  await page.reload();
  await expect(page.locator('.script-rule-row').first()).toContainText('脚本须使用麦咖啡芝士浓奶铁全称');
  await page.screenshot({path:'test-results/script-rule-table.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
});
