import { test, expect } from '@playwright/test';

test('脚本无未通过项可正式提交、刷新保留状态并可逐条提出异议（固定响应）', async ({ page, request }) => {
  test.skip(process.env.E2E_DISCUSSION_FIXTURE !== '1', '仅使用隔离固定响应');
  const headers = () => ({ 'Idempotency-Key': crypto.randomUUID() });
  const project = (await (await request.post('/api/v1/projects', { headers: headers(), data: { name: `正式提交-${Date.now()}`, brandName: '品牌A', platforms: ['xiaohongshu'] } })).json()).data;
  const rule = { text: '展示品牌A产品', criterion: '产品可辨认即可', importance: 'must', category: '产品' };
  const task = (await (await request.post(`/api/v1/projects/${project.id}/publish-task`, { headers: headers(), data: { creatorName: '正式提交达人', platform: 'xiaohongshu', scriptRules: [rule], videoRules: [rule], scriptConfirmed: true, videoConfirmed: true, confirmationNote: '固定测试' } })).json()).data.id;
  const cfg = (await (await request.get('/api/v1/settings/models')).json()).data;
  expect((await request.put('/api/v1/settings/models', { data: { endpoint: 'https://models.example.com/v1', model: 'e2e-discussion-fixture', apiKey: 'sk-test-fixture', revision: cfg.revision } })).ok()).toBeTruthy();
  await request.post(`/api/v1/tasks/${task}/scripts`, { headers: headers(), data: { inputType: 'text', text: 'E2E_PASS 展示品牌A产品。' } });
  const view = (await (await request.get(`/api/v1/tasks/${task}/workflow`)).json()).data;
  const review = (await (await request.post(`/api/v1/tasks/${task}/workflow/script-reviews`, { headers: headers(), data: { scriptVersionId: view.currentScript.scriptVersionId, contextKey: view.contextKey, configRevision: cfg.revision + 1, allowRealCall: true } })).json()).data;
  expect(review.status).toBe('succeeded');
  await page.addInitScript(() => localStorage.setItem('review-demo-role', 'creator'));
  await page.goto(`/creator/projects/${project.id}/tasks/${task}`);
  await expect(page.getByText('这次审核意见，你准备怎么处理？', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '收到，我去修改', exact: true })).toHaveCount(0);
  expect((await (await request.get('/api/v1/workflow/review-queue')).json()).data.filter((r: { id: string }) => r.id === task)).toHaveLength(0);
  const left = await page.locator('.creator-reader-card').first().boundingBox();
  const middle = await page.locator('.creator-reader-card').last().boundingBox();
  const right = await page.locator('.script-review-aside').boundingBox();
  expect(left!.x + left!.width).toBeLessThanOrEqual(middle!.x);
  expect(middle!.x + middle!.width).toBeLessThanOrEqual(right!.x);
  await page.getByRole('button', { name: '提交品牌', exact: true }).click();
  await expect(page).toHaveURL(/\/creator$/);
  await expect(page.getByRole('heading', { name: '我的合作', exact: true })).toBeVisible();
  await expect(page.getByRole('article', { name: '脚本交付', exact: true })).toContainText('等待品牌复核');
  expect((await (await request.get('/api/v1/workflow/review-queue')).json()).data.filter((r: { id: string }) => r.id === task)).toHaveLength(1);
  await page.screenshot({path:'test-results/script-three-column.png'});
  await page.reload();
  await page.goto(`/creator/projects/${project.id}/tasks/${task}`);
  await expect(page.getByRole('button', { name: '已提交品牌', exact: true })).toBeDisabled();
  const after = (await (await request.get(`/api/v1/tasks/${task}/workflow`)).json()).data;
  expect(after.scriptReviews).toHaveLength(view.scriptReviews.length + 1);
  expect(after.scriptReview.id).toBe(review.id);
  await page.getByRole('button', { name: '我对 AI 有异议', exact: true }).click();
  await page.getByText('通过 1 项', { exact: true }).click();
  await page.getByRole('button', { name: '对这条提出异议', exact: true }).click();
  await page.getByLabel('异议具体理由', { exact: true }).fill('对本条规则解释有异议，请品牌核对。');
  await page.getByRole('button', { name: '提交异议给品牌', exact: true }).click();
  await expect(page.getByText('对本条规则解释有异议，请品牌核对。', { exact: true })).toBeVisible();
});
